# Walking Simulator: Тени Старого Дома
# main2_grok_v1.5 — скрытие предметов, обманки, тройной стук, расширенные взаимодействия.
# Без характеристик: только инвентарь и открытые флаги.
# Версия 1.5: заметный объём контента и логики поверх v1, без смены архитектуры на v2.

VERSION = "1.5"


def normalize(text):
    return text.strip().lower()


def has_any(text, *words):
    t = normalize(text)
    return any(w in t for w in words)


def show_inventory(inventory):
    if not inventory:
        print("  (пусто)")
    else:
        for item in sorted(inventory):
            print(f"  - {item}")


def parse_intent(raw):
    t = normalize(raw)
    if not t:
        return "empty", t
    if t in ("инвентарь", "вещи", "сумка", "i"):
        return "inventory", t
    if t in ("осмотреться", "осмотр", "look", "о"):
        return "look_around", t
    if t in ("помощь", "help", "?", "х"):
        return "help", t
    if has_any(t, "слушать", "прислуша"):
        return "listen", t
    if has_any(t, "использовать", "применить", "открыть", "ударить", "вставить",
               "сломать", "толкнуть", "потянуть", "пнуть", "ковыр", "поддеть"):
        return "use", t
    if has_any(t, "взять", "поднять", "подобрать", "забрать", "сдвинуть", "достать"):
        return "take", t
    if has_any(t, "осмотреть", "посмотреть", "глянуть", "заглянуть", "проверить",
               "трогать", "тронуть", "потрогать", "пощупать", "потрогать"):
        return "examine", t
    if has_any(t, "стучать", "постучать", "стук"):
        return "knock", t
    if has_any(t, "обойти", "двор", "кругом"):
        return "go_around", t
    if has_any(t, "войти", "пройти"):
        return "enter", t
    if has_any(t, "уйти", "уходить", "сбежать", "бежать"):
        return "leave", t
    return "keyword", t


def print_help():
    print(
        "\nПодсказка:\n"
        "  • Номер действия (1, 2, 3…) или слова из описания сцены\n"
        "  • осмотреть / взять / использовать / слушать\n"
        "  • «осмотреться» — снова сцена\n"
        "  • «инвентарь» — вещи с собой\n"
        "  • «помощь» — этот текст\n"
        "Не всё важное лежит на виду. Иногда нужна подсказка — из текста, "
        "записки или внимательного осмотра замка. Часть находок — просто мусор."
    )


def knows_key_hint(flags):
    """Ключ «существует» для игрока только после явной подсказки."""
    return bool(
        flags.get("note_read")
        or flags.get("lock_hint_front")
        or flags.get("lock_hint_back")
        or flags.get("whisper_key_hint")
    )


def grant_decoy(inventory, flags, item_key, flag_name, pickup_text):
    if item_key in inventory:
        return False
    inventory.add(item_key)
    flags[flag_name] = True
    print(pickup_text)
    return True


# ─────────────────────────────────────────────────────────────
# СЦЕНА 1. Перед домом
# ─────────────────────────────────────────────────────────────

def scene_front(state):
    inventory = state["inventory"]
    flags = state["flags"]

    def describe():
        print("\n" + "─" * 50)
        print(f"ПЕРЕД ДОМОМ  ·  v{VERSION}")
        print("─" * 50)
        print(
            "Вечернее небо цвета старого синяка. Пустырь вокруг вытоптан до жёсткой "
            "глины; редкая пожухлая трава лежит пластами, будто её прижали ладонью. "
            "Дом стоит чуть криво — словно осел на один бок за десятилетия дождей. "
            "Обшивка потемнела, в щелях чернеет то, во что не хочется смотреть слишком долго.\n\n"
            "Крыльцо покосилось. Доски стоптаны посередине, по краям — липкая тёмная "
            "плёнка, похожая на смолу или на что-то, что вытекало сверху и засохло. "
            "Дверь в глубокой раме закрыта; ручка стёрта до тусклого металла. "
            "Слева от двери — окно: стекло мутное, в разводах от дождя, словно на него "
            "дышали изнутри слишком часто.\n\n"
            "Перила дрожат от ветра. Под ступенями — щель в сырую темноту. "
            "Вбок уходит узкая тропинка, примятая чьими-то шагами. "
            "У края крыльца валяется обломок ветки; в пыли у стены — что-то мелкое, "
            "блестящее на миг, когда ветер сдувает пепел."
        )
        if flags.get("rail_examined") and "гвоздь" not in inventory:
            print("У основания перил, в трещине доски, торчит ржавый гвоздь.")
        if flags.get("note_seen") and not flags.get("note_taken"):
            print("На внешнем краю подоконника — сложенный клочок бумаги, придавленный пылью.")
        if flags.get("knock_count", 0) >= 1:
            print("Дверь после стука кажется… внимательнее. Или это только холод.")
        if flags.get("triple_knock"):
            print("Рама чуть смещена. Дом помнит третий удар.")
        print(
            "\n1. Постучать в дверь\n"
            "2. Заглянуть в окно\n"
            "3. Обойти дом вокруг\n"
            "4. Осмотреться ещё раз"
        )

    def do_knock():
        """Расширенный стук: меняющийся звук; третий — событие, если нет осторожности от записки."""
        n = flags.get("knock_count", 0) + 1
        flags["knock_count"] = n
        flags["knocked"] = True

        if n == 1:
            print(
                "\nТы поднимаешь руку и стучишь костяшками. Звук короткий, сухой — "
                "дерево отвечает как пустая бочка. Удар уходит внутрь и гаснет, "
                "не найдя эха. За дверью на секунду шевелится воздух: не шаг, "
                "скорее смещение пыли."
            )
            print("Тишина после этого кажется чуть плотнее, чем до стука.")
            if flags.get("note_read"):
                print("(Вспоминаешь строку про «трижды». Пока — один.)")
            return None

        if n == 2:
            print(
                "\nВторой стук. На этот раз ответ другой: не сухой стук дерева, "
                "а глухой, влажный отзвук — будто под обшивкой кто-то приложил "
                "ладонь к той же точке, смягчая удар. Звук ниже. Дольше. "
                "Между ударом и тишиной слышен тонкий скрежет — как ноготь по металлу замка "
                "изнутри."
            )
            print(
                "Ручка на миг будто тяжелеет. Или пальцы просто окоченели."
            )
            if flags.get("note_read"):
                print(
                    "Записка жжёт карман: «Не стучи трижды.» Два — уже слишком близко."
                )
            else:
                print(
                    "Что-то в тоне ответа не совпадает с первым стуком. "
                    "Дом… подстроился?"
                )
            return None

        if n >= 3:
            if flags.get("triple_knock"):
                print(
                    "\nДовольно. Дверь уже ответила на третий раз. "
                    "Ещё стучать — бить по тому, что уже открыто или уже слушает."
                )
                return None

            if flags.get("note_read"):
                print(
                    "\nТы знаешь, что не надо. И всё же рука поднимается. "
                    "Третий стук — и звук уже не твой: он выходит изнутри навстречу, "
                    "совпадая с ударом до дрожи в зубах. Замок щёлкает сам. "
                    "Дверь приоткрывается на ширину ладони. Из щели пахнет сырым подвалом "
                    "и чем-то сладковато-тухлым, как забытые цветы в воде."
                )
                print(
                    "Никто не выглядывает. Но порог ждёт. "
                    "Можно войти — или захлопнуть и искать другой путь."
                )
                flags["triple_knock"] = True
                flags["door_ajar"] = True
                flags["triple_knock_knew"] = True
                return None

            # Без записки — полная сцена «трижды»
            print(
                "\nТретий стук. Звук на этот раз высокий, стеклянный — "
                "совсем не дерево. Словно ударили по горлу пустого кувшина. "
                "Ответ приходит сразу: скрежет ригеля, тяжёлый вздох петель, "
                "и дверь медленно уходит внутрь сама, без твоей руки на ручке."
            )
            print(
                "За порогом — чернота коридора. На полу, у самой кромки света, "
                "на миг мелькает край босой ступни — и исчезает вглубь. "
                "Холод вытекает наружу, как вода из прорванной бочки."
            )
            print(
                "Дом открыл тебе фасад. Можно переступить порог — "
                "или отступить и обойти, пока разум ещё спорит со страхом."
            )
            flags["triple_knock"] = True
            flags["door_ajar"] = True
            flags["invited_by_knock"] = True
            return None

    describe()

    while True:
        raw = input("\n> ")
        t = normalize(raw)
        intent, _ = parse_intent(raw)

        if t == "1":
            intent = "knock"
            t = "постучать дверь"
        elif t == "2":
            intent = "examine"
            t = "заглянуть окно"
        elif t == "3":
            intent = "go_around"
            t = "обойти дом"
        elif t == "4":
            intent = "look_around"

        if intent == "help":
            print_help()
            continue
        if intent == "inventory":
            print("С собой:")
            show_inventory(inventory)
            continue
        if intent == "look_around" or intent == "empty":
            describe()
            continue
        if intent == "leave":
            print(
                "\nПустырь за спиной — серое ничто. Уходить сейчас значит "
                "оставить имя на ветру. Ноги не слушаются. Ты остаёшься у дома."
            )
            continue

        # ── стук ──
        if intent == "knock" or (
            intent == "keyword" and has_any(t, "дверь") and has_any(t, "стук", "стучать")
        ):
            do_knock()
            continue

        # ── обойти ──
        if intent == "go_around" or (
            has_any(t, "тропинка", "обойти", "кругом") and intent != "examine"
        ):
            print(
                "\nТы ступаешь на тропинку. Трава хрустит, как сухие жилы. "
                "Стена дома рядом — в ней тонкие трещины, из которых тянет "
                "затхлым теплом. Ветер срывается с угла; изнутри, сквозь щели, "
                "доносится неровный шорох, будто кто-то волочит ткань по полу. "
                "Ты выходишь на задний двор…"
            )
            return "backyard"

        if has_any(t, "тропинка") and intent == "examine":
            print(
                "\nТропинка узкая, примята неоднократно. В глине — отпечатки, "
                "размытые дождём: то ли босые, то ли в мягкой обуви. "
                "Ведёт вдоль стены, туда, где дом можно обойти."
            )
            flags["path_examined"] = True
            continue

        # ── слушать ──
        if intent == "listen" or has_any(t, "слушать"):
            if has_any(t, "дверь", "дом", "замок") or t in ("слушать", "прислушаться"):
                print(
                    "\nТы прижимаешься ухом к холодной поверхности. Сначала — только "
                    "собственный пульс. Потом: отдалённый скрип половицы. "
                    "Капля. Ещё капля. И очень тихий звук — как будто кто-то "
                    "медленно проводит ногтем по другой стороне двери, сверху вниз."
                )
                if flags.get("knock_count", 0) >= 2:
                    print(
                        "После второго стука этот ноготь будто ждал у замка."
                    )
                flags["listened_front"] = True
                continue

        if intent in ("examine", "keyword", "take", "use", "enter"):
            # —— дверь, замок, ручка, петли, рама ——
            if has_any(t, "дверь", "замок", "ручка", "петл", "рам", "крыльцо", "ригел", "порог"):
                # войти
                if intent == "enter" or has_any(t, "войти") or (
                    has_any(t, "открыть") and not has_any(t, "гвоздь", "камень", "ветк", "пуговиц", "ткан")
                ):
                    if flags.get("door_ajar"):
                        print(
                            "\nТы толкаешь уже живую щель. Петли стонут. "
                            "Коридор принимает тебя без света."
                        )
                        flags["entered_front"] = True
                        if flags.get("invited_by_knock"):
                            flags["entered_as_guest"] = True
                        return "inside"
                    if "ключ" in inventory:
                        print(
                            "\nКлюч входит туго, металл на металл. Оборота хватает: "
                            "ригель уходит. Дверь поддаётся с вздохом старого меха."
                        )
                        flags["entered_front"] = True
                        flags["used_key_front"] = True
                        return "inside"
                    print(
                        "\nДверь не поддаётся. Ручка ходит в гнезде, но ригель держит. "
                        "Можно стучать. Можно искать, чем открыть. Можно обойти."
                    )
                    continue

                # использование предметов на дверь
                if intent == "use" or has_any(t, "гвоздь", "ключ", "камень", "ветк", "пуговиц",
                                              "ткан", "монет", "осколок"):
                    if "ключ" in inventory and has_any(t, "ключ"):
                        print(
                            "\nЗубцы ключа находят пазы, будто замок ждал именно эту "
                            "стёртую форму. Щелчок. Тяжёлая тишина. Дверь свободна."
                        )
                        flags["entered_front"] = True
                        flags["used_key_front"] = True
                        return "inside"
                    if "гвоздь" in inventory and has_any(t, "гвоздь"):
                        print(
                            "\nТы вводишь гвоздь в скважину. Скрежет. Что-то цепляется — "
                            "и срывается. Замок не из тех, что сдаются на ржавчину и упрямство. "
                            "Лишь царапина на губке замка: свежий металл под слоем окиси."
                        )
                        flags["tried_nail_on_door"] = True
                        # слабая подсказка без прямой выдачи ключа
                        if not knows_key_hint(flags):
                            print(
                                "По форме скважины ясно: ключ был — длинный, с широкой бородкой. "
                                "Такой не валяется у порога. Его где-то прячут."
                            )
                            flags["lock_hint_front"] = True
                        continue
                    if "камень" in inventory and has_any(t, "камень"):
                        print(
                            "\nКамень тяжёл. Удар по филёнке оставил бы след — и разбудил бы "
                            "всё, что спит за стенами. Ты опускаешь руку. Не сейчас. Не в лицо дому."
                        )
                        flags["almost_stone_door"] = True
                        continue
                    if "ветка" in inventory and has_any(t, "ветк"):
                        print(
                            "\nВетка ломается о ручку с сухим треском. Бесполезно. "
                            "Щепки падают на крыльцо, как мелкие кости."
                        )
                        continue
                    if "пуговица" in inventory and has_any(t, "пуговиц"):
                        print(
                            "\nПуговица не ключ. Ты прижимаешь её к скважине — холод к холоду — "
                            "и убираешь, чувствуя себя глупо. И всё же на миг показалось, "
                            "что металл замка стал чуть теплее."
                        )
                        continue
                    if "тряпица" in inventory and has_any(t, "ткан", "тряп"):
                        print(
                            "\nТы обматываешь ручку тряпицей — от холода или от того, "
                            "чтобы не оставить следов. Ручка всё так же не открывает дверь."
                        )
                        continue
                    if "монета" in inventory and has_any(t, "монет"):
                        print(
                            "\nМонета не проходит в скважину. Звякнув о губку замка, "
                            "она падает в пыль; ты поднимаешь её снова. Ничего."
                        )
                        continue
                    if has_any(t, "пнуть", "ударить") and not has_any(t, "камень"):
                        print(
                            "\nУдар ногой. Доска дрогнула, боль стрельнула в пятку. "
                            "Дом не сдвинулся. Только с крыши осыпалась стружка пыли."
                        )
                        flags["kicked_door"] = True
                        continue
                    if has_any(t, "толкнуть", "потянуть"):
                        print(
                            "\nТянешь на себя — мёртвый вес. Толкаешь — то же. "
                            "Щели нет ни на волос, пока замок не решит иначе."
                        )
                        if flags.get("door_ajar"):
                            print("Впрочем, сейчас щель уже есть — после третьего стука.")
                        continue
                    print(
                        "\nУточни: использовать <предмет> на дверь / замок / ручку."
                    )
                    continue

                # осмотр частей двери
                if has_any(t, "ручка"):
                    print(
                        "\nРучка вытерта до серого блеска — её трогали часто и давно. "
                        "Под ней тёмный ореол: пот, грязь, время. Поворачивается "
                        "вхолостую на четверть оборота и упирается в ригель."
                    )
                    flags["handle_examined"] = True
                    continue
                if has_any(t, "петл"):
                    print(
                        "\nПетли забиты старой смазкой и ржавчиной. Верхняя чуть "
                        "выступает — дверь садилась годами. Снять их голыми руками нельзя."
                    )
                    if "гвоздь" in inventory and (intent == "use" or has_any(t, "гвоздь")):
                        print(
                            "Гвоздем поддеваешь край — отлетает чешуя ржавчины. "
                            "Петля цела. Дом не отдаст дверь так просто."
                        )
                    continue
                if has_any(t, "замок", "скважин", "ригел"):
                    print(
                        "\nЗамок врезной, тяжёлый. Скважина не круглая — вытянутая, "
                        "со следами многократного ключа. Края губки залощены. "
                        "Кто-то отпирал эту дверь сотни раз… и потом перестал."
                    )
                    flags["lock_examined"] = True
                    if not knows_key_hint(flags):
                        print(
                            "Такой замок не вскроешь веткой. Ему нужен свой ключ — "
                            "широкая бородка, длинный стержень. Где его держат, когда "
                            "не носят с собой, — обычно не на видном крючке у входа."
                        )
                        flags["lock_hint_front"] = True
                    elif flags.get("note_read"):
                        print("Записка уже сказала, где искать. Осталось проверить двор.")
                    continue
                if has_any(t, "порог"):
                    print(
                        "\nПорог стёрт посередине. В трещине — чёрная крошка, похожая "
                        "на засохшую землю с босых ног. Ничего, что можно взять."
                    )
                    continue
                if has_any(t, "крыльцо"):
                    print(
                        "\nКрыльцо держится на честном слове и двух балках. "
                        "Ступать осторожно: одна доска ходит ходуном."
                    )
                    flags["porch_examined"] = True
                    continue

                # общий осмотр двери
                print(
                    "\nДверь из тёмных филёнок, когда-то крашенных, теперь — матовых, "
                    "как засохшая кровь под лаком. Рама глубокая, в ней скапливается "
                    "холод. Замок. Ручка. Петли. Можно стучать, слушать, ковырять, "
                    "толкать — дом терпит осмотр, но не пускает без причины."
                )
                if flags.get("door_ajar"):
                    print("Сейчас она не заперта до конца: после третьего стука осталась щель.")
                flags["door_examined"] = True
                continue

            # —— окно / подоконник ——
            if has_any(t, "окно", "стекло", "подоконник"):
                if intent == "use" and "камень" in inventory and has_any(t, "камень"):
                    print(
                        "\nКамень уже у виска стекла. В отражении грязи — твоё лицо. "
                        "Удар разбудил бы не только стекло. Ты медленно опускаешь руку."
                    )
                    flags["almost_broke_window"] = True
                    continue
                if intent == "use" and "тряпица" in inventory and has_any(t, "ткан", "тряп"):
                    print(
                        "\nТы протираешь круг на стекле. Грязь отходит неохотно. "
                        "Круг всё равно мутный — будто муть сидит в самом стекле, не на нём."
                    )
                    flags["window_wiped"] = True
                    # записка становится заметнее
                    if not flags.get("note_taken"):
                        print(
                            "У внешнего края подоконника, где тряпка сдвинула пыль, "
                            "лежит сложенный клочок бумаги."
                        )
                        flags["note_seen"] = True
                    continue
                if intent == "use" and "гвоздь" in inventory and has_any(t, "гвоздь"):
                    print(
                        "\nГвоздь царапает раму окна. Под слоем краски — светлое дерево. "
                        "Стекло не поддеть: замазка держит, как дёсны."
                    )
                    continue

                print(
                    "\nТы приближаешься к окну. Холод идёт от стекла сильнее, чем от воздуха. "
                    "Внутри — густая темнота, и в ней медленно складывается силуэт: плечи, "
                    "наклон головы. Он поворачивается к тебе без спешки. Глаз не видно — "
                    "только провалы. Рука поднимается и указывает вдоль стены, туда, "
                    "где тропинка уводит за угол. Потом силуэт редеет, как дым в тяге, "
                    "и комнаты снова нет — только твоё слабое отражение."
                )
                flags["window_seen"] = True
                flags["silhouette_seen"] = True
                # записка не кричит; лёгкий намёк
                if not flags.get("note_taken"):
                    if flags.get("window_wiped") or flags.get("sill_examined"):
                        print("На подоконнике снаружи — бумага, сложенная вдвое.")
                        flags["note_seen"] = True
                    else:
                        print(
                            "На внешнем крае подоконника пыль лежит неровно — "
                            "будто что-то тонкое недавно сдвинули или придавили."
                        )
                        flags["sill_odd"] = True
                continue

            if has_any(t, "пыл") and flags.get("sill_odd") and not flags.get("note_taken"):
                print(
                    "\nТы смахиваешь пыль. Под ней — сложенная записка, края влажные от воздуха."
                )
                flags["note_seen"] = True
                continue

            # —— записка ——
            if has_any(t, "записк", "бумаг", "клочок"):
                if not flags.get("note_seen") and not flags.get("note_taken"):
                    if flags.get("sill_odd"):
                        print(
                            "\nТы внимательнее смотришь на подоконник. Да — бумага. "
                            "Сложенная, почти одного цвета с пылью."
                        )
                        flags["note_seen"] = True
                    else:
                        print(
                            "\nПока ты не видел записки. Может, она есть — "
                            "там, где пыль лежит странно: у окна, на подоконнике."
                        )
                    continue
                if "записка" in inventory or flags.get("note_taken"):
                    print(
                        "\nЗаписка с тобой. Чернила расплылись, но читается:\n"
                        f"  «{state['name']}… ключ — под камнем у яблони. "
                        f"Не стучи трижды. Он стучит в ответ.»"
                    )
                    flags["note_read"] = True
                    continue
                if intent == "take" or has_any(t, "взять", "подобрать"):
                    inventory.add("записка")
                    flags["note_taken"] = True
                    flags["note_seen"] = True
                    flags["note_read"] = True
                    print(
                        "\nБумага холодная, почти влажная. Почерк дрожит:\n"
                        f"  «{state['name']}… ключ — под камнем у яблони. "
                        f"Не стучи трижды. Он стучит в ответ.»"
                    )
                    continue
                if intent == "examine" or intent == "keyword":
                    inventory.add("записка")
                    flags["note_taken"] = True
                    flags["note_seen"] = True
                    flags["note_read"] = True
                    print(
                        "\nРазворачиваешь. Строки ведут себя как шёпот:\n"
                        f"  «{state['name']}… ключ — под камнем у яблони. "
                        f"Не стучи трижды. Он стучит в ответ.»\n"
                        "Ты прячешь бумагу, не глядя по сторонам."
                    )
                    continue
                continue

            # —— перила / гвоздь (гвоздь спрятан за осмотром) ——
            if has_any(t, "перил", "гвоздь"):
                if has_any(t, "гвоздь") or flags.get("rail_examined"):
                    if "гвоздь" in inventory:
                        print("\nГвоздь у тебя: длинный, ржавый, кончик ещё злой.")
                        if intent == "use":
                            print("Можно применить к замку, раме, петлям — если укажешь цель.")
                        continue
                    if not flags.get("rail_examined") and not has_any(t, "гвоздь"):
                        pass  # fall to rail examine
                    else:
                        if intent == "take" or has_any(t, "взять", "выдернуть", "поднять"):
                            inventory.add("гвоздь")
                            flags["nail_taken"] = True
                            print(
                                "\nГвоздь выходит из дерева с сухим хрустом, "
                                "будто доска не хотела отдавать. Тянет ржавчиной и сыростью."
                            )
                            continue
                        print(
                            "\nВ трещине перильной стойки — длинный гвоздь, вбитый криво. "
                            "Держится слабо. Можно вытащить."
                        )
                        flags["rail_examined"] = True
                        continue
                print(
                    "\nПерила из посеревшего дерева. Поручень липкий от старого налёта. "
                    "Стойка треснула сверху донизу. В трещине что-то металлическое "
                    "ломает свет — не сразу поймёшь, гвоздь это или осколок скобы."
                )
                flags["rail_examined"] = True
                continue

            # —— щель / ступени (обманки: монета, пуговица) ——
            if has_any(t, "щель", "ступен", "подступ"):
                print(
                    "\nТы опускаешься, запускаешь руку под ступени. Сыро. Паутина "
                    "липнет к запястью. Пальцы находят рыхлую землю, обломок щепки…"
                )
                flags["checked_under_steps"] = True
                if "монета" not in inventory:
                    print(
                        "…и круглую жёсткость. Монета? Старая, стёртая до беспамятства. "
                        "Год не читается. Можно взять — или оставить земле."
                    )
                    flags["coin_seen"] = True
                else:
                    print("Там, где была монета, теперь только ямка в прахе.")
                if "пуговица" not in inventory and flags.get("porch_examined"):
                    print(
                        "Глубже, у дальней балки, перекатывается гладкая пуговица с костяным матовым блеском."
                    )
                    flags["button_seen"] = True
                continue

            if has_any(t, "монет"):
                if not flags.get("coin_seen") and "монета" not in inventory:
                    print("\nМонеты на виду нет. Может, под ступенями?")
                    continue
                if "монета" in inventory:
                    print("\nСтёртая монета. Не платёж — просто кружок мёртвого металла.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "монета", "coin_taken",
                        "\nМонета лязгает в ладони. Холодная. Бесполезная. И всё равно — твоя."
                    )
                    continue
                print("\nСтёртая монета в грязи под крыльцом. Можно подобрать.")
                continue

            if has_any(t, "пуговиц"):
                if "пуговица" in inventory:
                    print("\nКостяная пуговица. С двух дырок смотрит темнота.")
                    continue
                if not flags.get("button_seen") and not flags.get("checked_under_steps"):
                    print("\nПуговицы не видно. Осмотри крыльцо и щель под ступенями.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    flags["button_seen"] = True
                    grant_decoy(
                        inventory, flags, "пуговица", "button_taken",
                        "\nПуговица лёгкая, будто вырезанная из пальца, а не из кости животного. Наверное, просто кость."
                    )
                    continue
                flags["button_seen"] = True
                print("\nМатовая пуговица. К чужой одежде. Можно взять.")
                continue

            # —— ветка (обманка) ——
            if has_any(t, "ветк", "обломок"):
                if "ветка" in inventory:
                    print("\nСухая ветка. Ломается от взгляда. Оружием не будет.")
                    continue
                if intent == "take" or has_any(t, "взять", "поднять"):
                    grant_decoy(
                        inventory, flags, "ветка", "stick_taken",
                        "\nВетка хрустит в пальцах. Конец обломан недавно — или кажется, что недавно."
                    )
                    continue
                print(
                    "\nОбломок ветки у крыльца. Ничего особенного: серая кора, "
                    "лишённая гибкости. Можно поднять от нечего делать."
                )
                continue

            # —— блестящее в пыли (тряпица / фольга-обманка) ——
            if has_any(t, "блест", "пыл", "мелк", "пепел") and not has_any(t, "записк"):
                print(
                    "\nВ пыли у стены — не сокровище. Обрывок тряпицы, когда-то белой, "
                    "теперь цвета грязного снега. Рядом — чешуйка фольги или обёртки, "
                    "слишком ничтожная, чтобы брать."
                )
                flags["dust_examined"] = True
                if "тряпица" not in inventory:
                    print("Тряпицу можно подобрать.")
                    flags["rag_seen"] = True
                continue

            if has_any(t, "тряп", "ткан", "обрывок"):
                if "тряпица" in inventory:
                    print("\nГрязная тряпица. Пахнет пылью и слабым уксусом.")
                    continue
                if not flags.get("rag_seen") and not flags.get("dust_examined"):
                    print("\nТы не замечал ткани. Посмотри у стены, в пыли.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "тряпица", "rag_taken",
                        "\nТряпица мягкая от грязи. Сложить можно; отстирать — нет."
                    )
                    continue
                print("\nОбрывок ткани. Берутся такие вещи без причины — и носятся без пользы.")
                continue

            # —— дом / фасад / пустырь ——
            if has_any(t, "дом", "фасад", "обшив", "пустыр", "неб", "трав"):
                print(
                    "\nДом не красив. Он просто есть — тяжёлый, как чужая память, "
                    "которую тебе навязали. Окна — глазницы. Крыша просела. "
                    "Кажется, если отойти, он сделает шаг следом. Это, конечно, ветер."
                )
                continue

            if intent == "use":
                print("\nУточни предмет и цель: использовать <что> на <что>.")
                continue
            if intent == "take":
                print("\nЭтого на виду нет — или сначала нужно осмотреть место внимательнее.")
                continue

            print(
                "\nНе находится. Осмотрись снова или выбери номер. («помощь»)"
            )
            continue

        print("\nНе понял. Номер, слово из текста или «помощь».")


