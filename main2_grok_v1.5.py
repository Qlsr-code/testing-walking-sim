def scene_backyard(state):
    inventory = state["inventory"]
    flags = state["flags"]

    def describe():
        print("\n" + "─" * 50)
        print(f"ЗАДНИЙ ДВОР  ·  v{VERSION}")
        print("─" * 50)
        print(
            "Здесь ветер другой — ниже, злее, с запахом прелых яблок, которых нет. "
            "Задний двор зарос по пояс: жёсткие стебли, крапива, что-то вроде "
            "вьюнка, обхватившего столбик старой верёвки. Земля под ногами мягкая, "
            "пружинит, будто под дёрном не грунт, а слежавшаяся ткань.\n\n"
            "Яблоня стоит ближе к забору: ствол в лишайнике, ветки без листьев, "
            "как чертеж лёгких на чёрном стекле. У корней — тяжёлый серый камень, "
            "вросший краями; на нём иногда сидят птицы, судя по белёсым потёкам.\n\n"
            "Задняя дверь дома — ниже парадной, с ржавым засовом поперёк. "
            "Сарай в стороне накренился; на внешней стене у косяка висит мутное "
            "зеркало в трещиноватой раме. В траве у сарая — битая посуда, "
            "тёмный рот банки, что-то тряпичное, похожее на детскую куклу."
        )
        if flags.get("rock_moved"):
            if knows_key_hint(flags) and not flags.get("key_taken"):
                if flags.get("key_glint_seen"):
                    print("В ямке под камнем, если знать, куда смотреть, тускнеет металл.")
                else:
                    print("Камень сдвинут. Под ним — сырая ямка и комья земли.")
            else:
                print(
                    "Камень сдвинут. Под ним — тёмная влажная земля, "
                    "запах холода и червей. Ничего, что бросалось бы в глаза."
                )
        if flags.get("key_taken"):
            print("Ямка у корней яблони разрыта. Больше там нечего искать.")
        print(
            "\n1. Вернуться к парадному входу\n"
            "2. Осмотреться\n"
            "3. Подойти к задней двери"
        )

    describe()

    while True:
        raw = input("\n> ")
        t = normalize(raw)
        intent, _ = parse_intent(raw)

        if t == "1":
            print("\nТы обходишь дом по тропинке снова…")
            if "ключ" in inventory:
                go = input("Открыть парадную дверь ключом? (да/нет): ")
                if normalize(go) in ("да", "д", "yes", "y"):
                    print("\nКлюч. Щелчок. Фасад принимает тебя тише, чем задний двор.")
                    flags["entered_front"] = True
                    flags["used_key_front"] = True
                    return "inside"
            if flags.get("door_ajar"):
                go = input("Парадная дверь ещё приоткрыта после стука. Войти? (да/нет): ")
                if normalize(go) in ("да", "д", "yes", "y"):
                    flags["entered_front"] = True
                    return "inside"
            print("Любопытство тянет назад, во двор. Ответы пахнут яблоней и ржавчиной.")
            continue
        if t == "2":
            intent = "look_around"
        if t == "3":
            intent = "examine"
            t = "осмотреть заднюю дверь засов"

        if intent == "help":
            print_help()
            continue
        if intent == "inventory":
            print("С собой:")
            show_inventory(inventory)
            continue
        if intent == "look_around" or intent == "empty":
            describe()
            continue
        if intent == "leave":
            print("\nЗа забором — тот же пустырь. Уходить некуда. Только в дом или под яблоню.")
            continue

        if intent == "listen":
            print(
                "\nСарай пощёлкивает деревом. В доме — длинная пауза, потом "
                "один шаг наверху. Только один."
            )
            continue

        if intent == "knock":
            print(
                "\nТы стучишь в заднюю дверь. Засов дребезжит тонко, по-другому, "
                "чем дерево фасада. Изнутри — тишина, тяжёлая, как мокрое сукно. "
                "Ответа нет. Здесь дом не играет в эхо."
            )
            flags["knocked_back"] = True
            continue

        if intent in ("examine", "keyword", "take", "use", "enter"):
            # —— яблоня ——
            if has_any(t, "яблон", "дерев", "корн", "лишай"):
                print(
                    "\nКора слоится пластинами. Под лишайником — тёмные рубцы, "
                    "похожие на старые надрезы. Плодов нет и, кажется, не было годами. "
                    "У корней камень лежит так, словно его не бросили, а уложили."
                )
                flags["tree_examined"] = True
                # без прямого «под ним ключ»
                if knows_key_hint(flags) and not flags.get("key_taken"):
                    print(
                        "После слов о ключе взгляд сам цепляется за камень — "
                        "не за красоту, за возможность."
                    )
                continue

            # —— камень (ключ НЕ светится без подсказки) ——
            if has_any(t, "камень") and not has_any(t, "засов", "дверь"):
                if "камень" in inventory:
                    print("\nБулыжник тянет карман и плечо. Удобен, чтобы бить по металлу.")
                    if intent == "use":
                        print("Цель? Например: использовать камень на засов / зеркало.")
                    continue

                if intent == "take" or has_any(t, "поднять", "сдвинуть", "взять"):
                    inventory.add("камень")
                    flags["rock_moved"] = True
                    flags["rock_taken"] = True
                    if knows_key_hint(flags):
                        print(
                            "\nКамень отходит с влажным вздохом земли. "
                            "Под ним — ямка. Пока только земля и запах холода. "
                            "Если ключ здесь, его ещё надо найти — руками, не глазами."
                        )
                    else:
                        print(
                            "\nТы поднимаешь камень. Тяжёлый, в пятнах мха. "
                            "Под ним — сырая ямка: комья, белый корешок, "
                            "суетливое движение червя. Ничего блестящего. "
                            "Ничего, за чем стоило бы гнуть спину… если не знаешь, что ищешь."
                        )
                    continue

                if flags.get("rock_moved"):
                    print("\nКамень уже не на месте. Ямка открыта погоде.")
                else:
                    print(
                        "\nСерый, тяжёлый, вросший. Края обкатаны дождями. "
                        "Можно сдвинуть — из упрямства или из привычки искать "
                        "под камнями то, чего там обычно нет."
                    )
                continue

            # —— ямка / копать / ключ ——
            if has_any(t, "ямк", "копа", "земл", "черв", "корень") or (
                has_any(t, "ключ") and not has_any(t, "дверь", "засов", "замок")
            ):
                if "ключ" in inventory:
                    print("\nКлюч уже у тебя. Латунь отдала свой холод ладони.")
                    continue

                if not flags.get("rock_moved"):
                    if has_any(t, "ключ"):
                        if knows_key_hint(flags):
                            print(
                                "\nКлюча на виду нет. Подсказка вела к камню у яблони — "
                                "сначала камень, потом то, что под ним."
                            )
                        else:
                            print(
                                "\nТы не видишь ключа. И не уверен, что он вообще здесь есть. "
                                "Просто двор, грязь и ржавчина."
                            )
                    else:
                        print("\nЯмки не видно, пока камень лежит на месте.")
                    continue

                # камень сдвинут
                if has_any(t, "ключ") and not knows_key_hint(flags):
                    print(
                        "\nЗачем тебе ключ? Ты роешься в сырой земле без причины "
                        "и находишь только холод и запах глины. "
                        "Может, стоило сначала понять, что ищешь — "
                        "у замка, в записке, в чужих словах."
                    )
                    flags["dug_without_hint"] = True
                    continue

                if not knows_key_hint(flags):
                    # осмотр ямки без знания о ключе — обманка / пусто
                    if intent == "take" or has_any(t, "копа", "рыть", "искать"):
                        print(
                            "\nТы разгребаешь землю. Пальцы немеют. "
                            "Попадается гладкий камешек — не тот — и обломок корня. "
                            "Ничего, за что зацепилась бы надежда."
                        )
                        if "камешек" not in inventory:
                            print("Маленький камешек можно зачем-то взять. Или не брать.")
                            flags["pebble_seen"] = True
                        continue
                    print(
                        "\nСырая ямка. Червь. Запах. Если здесь и прятали что-то, "
                        "ты не знаешь вида находки — и потому не видишь её."
                    )
                    continue

                # есть подсказка + камень сдвинут
                if intent == "examine" and not has_any(t, "взять", "достать") and not flags.get("key_glint_seen"):
                    print(
                        "\nТы разгребаешь ямку уже целенаправленно — знаешь, что должно быть. "
                        "Земля липнет. Палец натыкается на жёсткий край… металл. "
                        "Тусклый. Прячется в комке, не блестит напоказ."
                    )
                    flags["key_glint_seen"] = True
                    continue

                if intent == "take" or has_any(t, "взять", "достать", "ключ", "копа", "рыть"):
                    if not flags.get("key_glint_seen") and intent == "examine":
                        pass
                    inventory.add("ключ")
                    flags["key_taken"] = True
                    flags["key_glint_seen"] = True
                    print(
                        "\nЛатунный ключ выходит из глины тяжёлым куском тишины. "
                        "Зубцы стёрты, стержень длинный — как тот, чей след ты "
                        "видел (или вообразил) в скважине фасада. "
                        "Ты вытираешь его о край одежды. Пятно не сходит."
                    )
                    continue

                if flags.get("key_glint_seen"):
                    print("\nВ ямке — ключ. Можно взять.")
                else:
                    print(
                        "\nЯмка ждёт рук. Подсказка уже есть — осталось искать не глазами, а пальцами."
                    )
                continue

            # —— камешек-обманка ——
            if has_any(t, "камешек", "камеш"):
                if "камешек" in inventory:
                    print("\nГладкий камешек. Греет карман и ничего не открывает.")
                    continue
                if not flags.get("pebble_seen") and not (
                    flags.get("rock_moved") and flags.get("dug_without_hint")
                ):
                    print("\nКамешка не видно.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "камешек", "pebble_taken",
                        "\nКамешек — тёплый от руки уже через минуту. Пустышка. Успокаивает."
                    )
                    continue
                print("\nМаленький, гладкий. Можно взять.")
                continue

            # —— засов / задняя дверь ——
            if has_any(t, "засов", "задн") or (
                has_any(t, "дверь") and not has_any(t, "парад")
            ):
                if intent == "use" or intent == "enter" or has_any(
                    t, "открыть", "ударить", "сбить", "ключ", "камень", "гвоздь", "осколок"
                ):
                    if "ключ" in inventory and has_any(t, "ключ"):
                        print(
                            "\nУ засова — скрытая скважина, забитая ржавой пылью. "
                            "Ключ входит. Ты поворачиваешь; механизм сопротивляется, "
                            "потом сдаётся. Засов отходит. Дверь внутрь — чернота и запах прели."
                        )
                        flags["entered_back"] = True
                        flags["used_key_back"] = True
                        return "inside"
                    if "камень" in inventory and has_any(t, "камень", "ударить", "сбить", "сломать"):
                        print(
                            "\nУдар. Металл взвизгивает. Второй удар — засов лопается, "
                            "обломок звякает о порог. Дверь вваливается внутрь. "
                            "Где-то в доме падает что-то тяжёлое: ответ на твой шум."
                        )
                        flags["entered_back"] = True
                        flags["forced_back"] = True
                        return "inside"
                    if "гвоздь" in inventory and has_any(t, "гвоздь"):
                        print(
                            "\nГвоздь слишком тонкий для засова. Царапаешь, злишься — "
                            "металл даже не заметляет. Нужен ключ или грубый вес."
                        )
                        flags["tried_nail_on_bolt"] = True
                        continue
                    if "осколок" in inventory and has_any(t, "осколок"):
                        print("\nОсколок крошится о засов. Кровь на пальце. Металл цел.")
                        continue
                    if "ветка" in inventory and has_any(t, "ветк"):
                        print("\nВетка щёлкает и умирает. Засов смеётся ржавчиной.")
                        continue
                    if intent == "enter" or has_any(t, "открыть"):
                        if "ключ" in inventory:
                            print("\nКлюч. Скрип. Ты внутри.")
                            flags["entered_back"] = True
                            flags["used_key_back"] = True
                            return "inside"
                        print("\nНе открыть. Засов и скрытый замок.")
                        continue
                    print("\nИспользуй предмет явно: ключ / камень на засов или дверь.")
                    continue

                print(
                    "\nЗасов лежит поперёк, тяжёлый, в хлопьях ржавчины. "
                    "Под ним угадывается личина замка — не с улицы ключ вставишь, "
                    "если не знаешь, куда жать. Филёнки двери в потёках."
                )
                flags["back_door_examined"] = True
                if not knows_key_hint(flags):
                    print(
                        "Замок здесь того же «семейства», что и на фасаде: "
                        "широкая бородка, длинный стержень. Ключ где-то на участке — "
                        "не в замке и не на гвозде у косяка."
                    )
                    flags["lock_hint_back"] = True
                continue

            if has_any(t, "замок") and flags.get("back_door_examined"):
                if not knows_key_hint(flags):
                    flags["lock_hint_back"] = True
                print(
                    "\nСкрытая скважина. Ржавая пыль. Ключ, если он есть, "
                    "должен пахнуть этой же пылью."
                )
                continue

            # —— сарай ——
            if has_any(t, "сарай"):
                print(
                    "\nВнутри: пыль столбом в полоске света из щели, пустые крюки, "
                    "запах прелого сена, которого нет. Пол — утрамбованная грязь. "
                    "Ни инструмента, ни лопаты. На стене снаружи — зеркало. "
                    "В углу травы у порога сарая валяется битая чашка и тёмная банка."
                )
                flags["shed_seen"] = True
                flags["junk_seen"] = True
                if not flags.get("shard_seen"):
                    print(
                        "Между стеблями иногда режет глаз тонкая грань — "
                        "стекло, но не сразу поймёшь, осколок ли."
                    )
                continue

            # —— зеркало ——
            if has_any(t, "зеркал"):
                if flags.get("mirror_broken"):
                    print("\nПустая рама. Осколки в траве мешают смотреть на себя.")
                    continue
                if intent == "use" and "камень" in inventory and has_any(t, "камень"):
                    print(
                        "\nУдар. Зеркало рвётся звоном. На миг в осколках — много тебя, "
                        "и ни одного… другого. Потом только трава и тишина громче ветра."
                    )
                    flags["mirror_broken"] = True
                    flags["shard_seen"] = True
                    continue
                if intent == "use" and "тряпица" in inventory and has_any(t, "тряп", "ткан"):
                    print(
                        "\nПротираешь. Муть не уходит — она в амальгаме. "
                        "Лицо становится чуть яснее и оттого хуже."
                    )
                    continue
                if intent == "use" and "пуговица" in inventory and has_any(t, "пуговиц"):
                    print(
                        "\nПуговица к стеклу — как глаз к глазу. Отражение не моргает. Ты — моргаешь."
                    )
                    continue
                print(
                    "\nМуть и трещины. В отражении — ты; губы в стекле шевелятся чуть раньше:\n"
                    f"  «{state['name']}… зайди. Пожалуйста.»\n"
                    "Голос не слышен. Только форма рта."
                )
                flags["mirror_seen"] = True
                # шёпот-подсказка о ключе — редкая, если долго смотреть и ещё нет hint
                if not knows_key_hint(flags) and flags.get("shed_seen"):
                    print(
                        "На выдохе, уже отворачиваясь, кажется, что стекло добавило беззвучно: "
                        "«…не в замке. Под тяжестью.»"
                    )
                    flags["whisper_key_hint"] = True
                continue

            # —— осколок (не сразу в общем describe) ——
            if has_any(t, "осколок", "стекл", "грань"):
                if "осколок" in inventory:
                    print("\nОстрый. Режет нитку и кожу. Не нож — но близко.")
                    continue
                if not flags.get("shed_seen") and not flags.get("mirror_broken") and not flags.get("junk_seen"):
                    print("\nСтекла на виду не видно. Загляни к сараю, в траву.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    inventory.add("осколок")
                    flags["shard_taken"] = True
                    flags["shard_seen"] = True
                    print(
                        "\nОсколок — от банки или от старого стекла. "
                        "Ты заворачиваешь край в край одежды."
                    )
                    continue
                flags["shard_seen"] = True
                print("\nТонкая грань в траве. Можно взять осторожно.")
                continue

            # —— обманки: банка, кукла, чашка ——
            if has_any(t, "банк"):
                if "банка" in inventory:
                    print("\nРжавая банка. Внутри — сухой прах и запах мышей. Пусто.")
                    continue
                if not flags.get("junk_seen") and not flags.get("shed_seen"):
                    print("\nБанки не замечал. У сарая в траве что-то тёмное.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "банка", "can_taken",
                        "\nБанка тяжёлая от ржавчины, не от содержимого. Крышки нет. Бери — носи — ничего."
                    )
                    flags["junk_seen"] = True
                    continue
                print(
                    "\nТёмное горло банки без этикетки. Пахнет железом и пылью. Можно взять."
                )
                flags["junk_seen"] = True
                continue

            if has_any(t, "кукл", "тряпич"):
                if "кукла" in inventory:
                    print(
                        "\nТряпичная кукла. Один шов — глаз — распорот. "
                        "Набивка лезет серым. Не талисман. Не ключ. Просто уродство."
                    )
                    continue
                if not flags.get("junk_seen") and not flags.get("shed_seen"):
                    print("\nКуклы не видно, пока не подойдёшь к хламу у сарая.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "кукла", "doll_taken",
                        "\nКукла весит мало и всё равно оттягивает руку. Ты берёшь её, не зная зачем."
                    )
                    flags["junk_seen"] = True
                    continue
                if intent == "use" and has_any(t, "гвоздь") and "гвоздь" in inventory:
                    print("\nГвоздь в тряпке. Жестоко и бессмысленно. Кукла не кричит.")
                    continue
                print(
                    "\nДетская кукла из мешковины, мокрая на вид, хотя сухая. "
                    "Один «глаз» — пуговичный — вырван. Можно поднять."
                )
                flags["junk_seen"] = True
                continue

            if has_any(t, "чашк", "посуд", "осколк посуд"):
                if flags.get("cup_examined"):
                    print("\nБитая чашка. Узор — мелкие розы, выцветшие до пятен. Острые края.")
                else:
                    print(
                        "\nЧашка расколота на три крупных куска. На донышке — тёмное кольцо "
                        "от чего-то, что давно выпили. Ничего внутри."
                    )
                flags["cup_examined"] = True
                flags["junk_seen"] = True
                if intent == "take":
                    print("Носить черепки нет смысла. Ты оставляешь их траве.")
                continue

            # —— трава / забор ——
            if has_any(t, "трав", "крапив", "забор", "верёв"):
                print(
                    "\nЗабор дырявый. Верёвка на столбике перетёрта. "
                    "Крапива жжётся, даже когда не трогаешь — память кожи. "
                    "В гуще у сарая — хлам: банка, кукла, чашка."
                )
                flags["junk_seen"] = True
                continue

            if intent == "use":
                if "ключ" in inventory and has_any(t, "ключ"):
                    print("\nКлюч — к двери или засову. Назови цель.")
                    continue
                if "камень" in inventory and has_any(t, "камень"):
                    print("\nКамень — на засов или зеркало, если решишься.")
                    continue
                if "кукла" in inventory and has_any(t, "кукл"):
                    print("\nКукла ни к чему не подходит. Только занимает руки.")
                    continue
                print("\nНеясно. Используй <предмет> на <цель из сцены>.")
                continue

            if intent == "take":
                print("\nНечего брать с таким именем — или сначала осмотри место.")
                continue

            print("\nНе видно. «осмотреться» или «помощь».")
            continue

        print("\nНе понял команду.")


# ─────────────────────────────────────────────────────────────
# СЦЕНА 3. Внутри дома
# ─────────────────────────────────────────────────────────────

def scene_inside(state):
    inventory = state["inventory"]
    flags = state["flags"]

    def describe():
        print("\n" + "─" * 50)
        print(f"ВНУТРИ ДОМА  ·  v{VERSION}")
        print("─" * 50)
        print(
            "Воздух внутри гуще улицы: сырое дерево, пыль, сладковатая гниль "
            "от чего-то, что забыли в стене. Коридор узкий. Обои когда-то были "
            "в мелкий рисунок — теперь это грязные разводы, похожие на карты "
            "несуществующих стран. Слева проём в гостиную; справа лестница "
            "уходит вверх в более густую темноту. На стене — портрет в тяжёлой "
            "раме. Под лестницей — шкаф, вросший в угол. У порога — сухие следы.\n\n"
            "На консоли у стены — пустая ваза и блеклый бумажный билет, "
            "будто выпавший из чужой книги."
        )
        if flags.get("forced_back"):
            print("Эхо падения ещё живёт в дальних комнатах. Тебя услышали.")
        if flags.get("triple_knock") or flags.get("entered_as_guest"):
            print("Дом принял тебя через фасад — слишком охотно. Пол чуть липнет к подошвам.")
        if flags.get("silhouette_seen") and flags.get("knocked"):
            print("Шорох наверху знаком: тот же ритм, что за окном и за дверью.")
        print(
            "\n1. Войти в гостиную\n"
            "2. Подняться по лестнице\n"
            "3. Осмотреться\n"
            "4. Уйти из дома"
        )

    describe()

    while True:
        raw = input("\n> ")
        t = normalize(raw)
        intent, _ = parse_intent(raw)

        if t == "1":
            intent = "examine"
            t = "осмотреть гостиную"
        elif t == "2":
            intent = "keyword"
            t = "лестница наверх"
        elif t == "3":
            intent = "look_around"
        elif t == "4":
            intent = "leave"

        if intent == "help":
            print_help()
            continue
        if intent == "inventory":
            print("С собой:")
            show_inventory(inventory)
            continue
        if intent == "look_around" or intent == "empty":
            describe()
            continue

        if intent == "leave" or has_any(t, "уйти", "выйти", "наружу"):
            print(
                "\nХолод улицы бьёт в лёгкие. Дом за спиной становится плоским, "
                "как декорация — пока не обернёшься. Ты не обернёшься."
            )
            print(f"\n«{state['name']}» ещё звучит — уже тише.")
            print("\n=== Концовка: Уход ===")
            return "end"

        if intent == "listen":
            print(
                "\nДом дышит скрипами. Наверху — пауза длиной в решение. "
                "В шкафу — ничего, пока не откроешь."
            )
            continue

        if intent == "knock":
            print("\nСтучишь по обоям изнутри. Глухо. Никто не обязан отвечать себе.")
            continue

        if intent in ("examine", "keyword", "take", "use", "enter", "go_around"):
            # —— гостиная ——
            if has_any(t, "гостиная", "гостиную", "камин"):
                print(
                    "\nГостиная под чехлами: формы мебели угадываются, как тела под простынями. "
                    "Камин чёрен, в золе — чужой узор пальцев. На столе — рамка фотографии: "
                    "лица размыты сыростью, одно чуть яснее. На обороте, чернилами, дрожью:"
                    f" «{state['name']}»."
                )
                flags["living_seen"] = True
                if "записка" in inventory and flags.get("note_read"):
                    print("Почерк совпадает с запиской с подоконника — до наклона буквы «т».")
                    flags["handwriting_match"] = True
                if flags.get("silhouette_seen"):
                    print("У окна — босые следы в пыли, ведущие от стекла к двери гостиной.")
                print(
                    "На каминной полке — огарок свечи в медном подсвечнике. "
                    "Рядом — сухие стебли чего-то, что когда-то было букетом."
                )
                flags["candle_seen"] = True
                flags["flowers_seen"] = True
                continue

            if has_any(t, "фото", "рамк"):
                if not flags.get("living_seen"):
                    print("\nФотографии здесь не видно. Может, в гостиной.")
                    continue
                print(
                    f"\nЛицо на снимке смотрит мимо тебя. На обороте — «{state['name']}». "
                    "Рамку не отдираешь: стекло липнет к пальцам холодом."
                )
                continue

            if has_any(t, "свеч", "огарок", "подсвечник"):
                if not flags.get("candle_seen") and not flags.get("living_seen"):
                    print("\nСвечи не видел. Каминная полка — в гостиной.")
                    continue
                if "свеча" in inventory:
                    print("\nОгарок крошится. Фитиль короткий. Без огня — бутафория.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    inventory.add("свеча")
                    flags["candle_taken"] = True
                    print("\nВоск липнет к ногтям. Подсвечник оставляешь — слишком заметен.")
                    continue
                if intent == "use" and has_any(t, "спич", "огонь"):
                    print("\nОгня нет. Карманы пусты на искру.")
                    continue
                print("\nКороткий огарок. Можно взять.")
                continue

            if has_any(t, "букет", "стебл", "цвет", "сух"):
                if not flags.get("flowers_seen") and not flags.get("living_seen"):
                    print("\nЦветов не замечал.")
                    continue
                if "сухоцвет" in inventory:
                    print("\nЛоманые стебли. Сыплются пыльцой-прахом. Ни к чему.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "сухоцвет", "flowers_taken",
                        "\nСтебли хрустят. Пахнут пылью, не летом. Обманка для рук."
                    )
                    continue
                print("\nМёртвый букет. Можно сгрести в горсть — зачем?")
                continue

            # —— ваза / билет (обманки в коридоре) ——
            if has_any(t, "ваз"):
                print(
                    "\nВаза пуста. Внутри — белый налёт и один сухой усик паука. "
                    "Дно не откручивается. Ничего."
                )
                flags["vase_examined"] = True
                if intent == "use" and "монета" in inventory and has_any(t, "монет"):
                    print("Монета звякает внутри вазы. Ты трясёшь — звякает. Достаёшь. Пустота.")
                continue

            if has_any(t, "билет", "бумаж"):
                if "билет" in inventory:
                    print(
                        "\nБилет на поезд, дата стёрта, станция назначения — размазана. "
                        "Мог быть твоим. Мог быть чьим угодно."
                    )
                    continue
                if intent == "take" or has_any(t, "взять"):
                    grant_decoy(
                        inventory, flags, "билет", "ticket_taken",
                        "\nБумага ломкая. Номер вагона не читается. Кладёшь в карман к прочему молчанию."
                    )
                    continue
                print(
                    "\nБлеклый проездной. Чернила убежали от времени. Можно взять."
                )
                continue

            # —— портрет / пластинка ——
            if has_any(t, "портрет", "картин"):
                print(
                    "\nКраска осыпалась пятнами. Глаза на холсте — те же провалы, "
                    "что у силуэта в окне. Рама тяжёлая, чуть отходит от стены справа."
                )
                flags["portrait_seen"] = True
                if intent == "take":
                    print("Снять портрет целиком — шум и вес. Не стоит.")
                continue

            if has_any(t, "рам") and flags.get("portrait_seen"):
                print(
                    "\nРама шатается. Между ней и стеной — узкая тьма. "
                    "Голыми пальцами не поддеть."
                )
                if "гвоздь" in inventory and (intent == "use" or has_any(t, "гвоздь", "поддеть")):
                    print(
                        "\nГвоздь входит в щель. Рама отходит. В нише — тонкая "
                        "зубчатая пластинка, холодная, с узором, от которого "
                        "чешутся зубы в памяти."
                    )
                    flags["portrait_opened"] = True
                elif "осколок" in inventory and (intent == "use" or has_any(t, "осколок")):
                    print(
                        "\nОсколок чуть гнётся и чуть крошится, но щель поддаётся. "
                        "В нише — зубчатая пластинка."
                    )
                    flags["portrait_opened"] = True
                elif intent == "use" and "монета" in inventory and has_any(t, "монет"):
                    print("\nМонета тонкая, но скользит. Не хватает жёсткости. Нужно острее.")
                continue

            if has_any(t, "портрет", "рам") and (
                "гвоздь" in inventory or "осколок" in inventory
            ) and (intent == "use" or has_any(t, "гвоздь", "осколок", "поддеть")):
                if not flags.get("portrait_opened"):
                    print(
                        "\nТы поддеваешь раму. Ниша. Пластинка."
                    )
                    flags["portrait_opened"] = True
                    flags["portrait_seen"] = True
                    continue

            if has_any(t, "пластинка", "ниш", "механизм", "зубц"):
                if not flags.get("portrait_opened"):
                    print("\nПластинки не видно. Осмотри портрет и раму.")
                    continue
                if "пластинка" in inventory:
                    print("\nЗубцы холодят кожу. К чему-то сверху — или к кому-то.")
                    continue
                if intent == "take" or has_any(t, "взять"):
                    inventory.add("пластинка")
                    flags["plate_taken"] = True
                    print("\nПластинка твоя. Карман становится тяжелее смысла.")
                    continue
                print("\nВ нише за рамой — пластинка. Можно взять.")
                continue

            # —— шкаф ——
            if has_any(t, "шкаф"):
                if flags.get("closet_open"):
                    print("\nШкаф открыт. Плечики. Нафталин. Тень на нижней полке гуще пыли.")
                    if flags.get("forced_back") and not flags.get("closet_lurker_done"):
                        print("Что-то в этой тени сжимается и расправляется — к тебе.")
                        if "осколок" in inventory or "гвоздь" in inventory:
                            weapon = "осколок" if "осколок" in inventory else "гвоздь"
                            print(
                                f"\nТы вскидываешь {weapon}. Короткий скрежет, запах сухого меха. "
                                "Тень осыпается прахом. На полке — клок ткани, как у куклы снаружи."
                            )
                            flags["closet_lurker_done"] = True
                            flags["lurker_repelled"] = True
                        elif "кукла" in inventory:
                            print(
                                "\nТы суёшь куклу в тьму, как плату. Шевеление стихает. "
                                "Кукла больше не в руке — шкаф забрал обмен. Жутко. Бессмысленно. Жив."
                            )
                            inventory.discard("кукла")
                            flags["closet_lurker_done"] = True
                            flags["lurker_paid_doll"] = True
                        else:
                            print(
                                "\nНечем встретить. Дверца захлопывается. Удар изнутри. "
                                "Тишина. Шкаф больше не твой."
                            )
                            flags["closet_lurker_done"] = True
                            flags["lurker_scared"] = True
                    elif flags.get("triple_knock") and not flags.get("closet_lurker_done"):
                        print(
                            "\nНа полке — только пыль. Но на миг мерещится босая ступня "
                            "в глубине, та самая, с порога. Моргнул — нет."
                        )
                        flags["closet_foot_seen"] = True
                    continue

                print(
                    "\nШкаф тёмный, дверца с защёлкой. Руками — ни с места. "
                    "Нужно тонкое: гвоздь, осколок."
                )
                if intent == "use" or has_any(t, "открыть", "гвоздь", "осколок", "ключ", "монет"):
                    if "гвоздь" in inventory and has_any(t, "гвоздь", "открыть"):
                        print("\nГвоздь. Скрип. Защёлка сдаётся. Шкаф открыт.")
                        flags["closet_open"] = True
                        continue
                    if "осколок" in inventory and has_any(t, "осколок", "открыть"):
                        print("\nОсколок входит в щель. Кровь. Защёлка. Открыто.")
                        flags["closet_open"] = True
                        continue
                    if "ключ" in inventory and has_any(t, "ключ"):
                        print("\nКлюч к шкафу не от этого замка.")
                        continue
                    if "монета" in inventory and has_any(t, "монет"):
                        print("\nМонета щёлкает и падает внутрь зазора. Не достать. Не открыть.")
                        continue
                    if has_any(t, "открыть"):
                        print("\nРуками нельзя. Гвоздь или осколок.")
                        continue
                continue

            # —— следы ——
            if has_any(t, "след", "гряз"):
                print(
                    "\nСледы от порога к лестнице. Размер — почти твой. "
                    "Или ты — почти их."
                )
                flags["tracks_seen"] = True
                if "тряпица" in inventory and intent == "use" and has_any(t, "тряп"):
                    print("Протираешь пол. Следы мажутся, не исчезают. Хуже.")
                continue

            # —— лестница / финал ——
            if has_any(t, "лестниц", "наверх", "вверх", "этаж"):
                print(
                    "\nКаждая ступень — чужой вес. Наверху дверь приоткрыта. "
                    "Комната: кровать с продавленным центром, стол, кресло у окна."
                )
                if (
                    flags.get("silhouette_seen")
                    or flags.get("mirror_seen")
                    or flags.get("triple_knock")
                    or flags.get("note_read")
                ):
                    print(
                        "В кресле — человек. Силуэт, набравший плотности.\n"
                        f"— Я ждал, {state['name']}. Голос — как твой, пропущенный через стену."
                    )
                    flags["met_echo"] = True
                    return ending_encounter(state)
                print(
                    "Кресло с отпечатком тела. Со стола свисает пустой лист. "
                    "Никого. Дом ещё не готов показать лицо — или ты не готов увидеть."
                )
                flags["upstairs_empty"] = True
                print("Можно «уйти» или искать на первом этаже то, что откроет ему рот.")
                continue

            if has_any(t, "коридор", "обои", "консол", "стен", "пол"):
                print(
                    "\nЦарапины на обоях — на высоте плеча. Кто-то шёл, держась. "
                    "Долго. Часто. Ваза. Билет. Портрет. Шкаф. Лестница."
                )
                continue

            if intent == "use":
                if "пластинка" in inventory and has_any(t, "пластинка"):
                    print("\nВнизу пластинке некуда. Наверх — к креслу, к нему.")
                    continue
                if "свеча" in inventory and has_any(t, "свеч"):
                    print("\nНет огня. Свеча — жест, не свет.")
                    continue
                if "билет" in inventory and has_any(t, "билет"):
                    print("\nБилет никуда не вкладывается. Поезд ушёл без даты.")
                    continue
                if "банка" in inventory and has_any(t, "банк"):
                    print("\nСтавишь банку на консоль. Дом не изменился. Ты — чуть стыдливее.")
                    continue
                if "ключ" in inventory and has_any(t, "ключ"):
                    print("\nВнутри этому ключу больше нечего открывать.")
                    continue
                print("\nУточни предмет и цель.")
                continue

            if intent == "take":
                print("\nНе находится под рукой.")
                continue

            print("\nНе замечаешь. «осмотреться».")
            continue

        print("\nНе понял.")


def ending_encounter(state):
    inventory = state["inventory"]
    flags = state["flags"]
    name = state["name"]

    print(
        "\nОн не торопит. Указывает на стул напротив.\n"
        "1. Сесть и слушать\n"
        "2. Спросить, кто он\n"
        "3. Уйти вниз молча"
    )
    if "камень" in inventory:
        print("4. Сжать камень")
    if "записка" in inventory and flags.get("note_read"):
        print("5. Протянуть записку")
    if "пластинка" in inventory:
        print("6. Протянуть пластинку")
    if flags.get("triple_knock"):
        print("7. Спросить про стук / дверь")

    while True:
        raw = input("\n> ")
        t = normalize(raw)

        if t == "3" or has_any(t, "уйти", "вниз", "молча"):
            print(
                f"\nТы уходишь. За спиной: «{name}…» — обида дома, не человека."
            )
            print("\n=== Концовка: Молчаливый уход ===")
            return "end"

        if t == "1" or has_any(t, "сесть", "слушать"):
            print(
                f"\nСадишься. — Добро пожаловать домой, {name}. — "
                "Молчание плотное, почти тёплое."
            )
            if flags.get("triple_knock") and not flags.get("note_read"):
                print(
                    "Внизу будто снова стучат — в тот же ритм, что ты. "
                    "Вы оба слушаете. Никто не идёт открывать."
                )
                print("\n=== Концовка: Третий удар ===")
            elif flags.get("knocked") and not flags.get("note_read"):
                print("Эхо стука снизу. Порог между вами тоньше воздуха.")
                print("\n=== Концовка: Порог ===")
            elif flags.get("handwriting_match"):
                print("Он знает про записку и фото. Круг на миг смыкается без боли.")
                print("\n=== Концовка: Воссоединение ===")
            else:
                print("\n=== Концовка: Тишина ===")
            return "end"

        if t == "2" or has_any(t, "кто", "спросить") and not has_any(t, "стук", "дверь"):
            print(
                f"\n— Я — то, что осталось от {name}. Ты ушёл. Я ждал. "
                "Дом держит нас, пока память не сойдётся."
            )
            if flags.get("forced_back"):
                print("— Ты вошёл силой. Стены запомнили. Тебе будет теснее.")
                print("\n=== Концовка: Непрошеный гость ===")
            elif flags.get("mirror_broken"):
                print("— Ты разбил зеркало. Отражений меньше. Иногда это милосердие.")
                print("\n=== Концовка: Без отражения ===")
            elif flags.get("triple_knock_knew"):
                print("— Ты знал про три раза. И всё равно. Храбрость и глупость — соседи.")
                print("\n=== Концовка: Предупреждённый ===")
            else:
                print("\n=== Концовка: Эхо ===")
            return "end"

        if t == "7" or (has_any(t, "стук", "трижд", "дверь") and flags.get("triple_knock")):
            print(
                "\n— Каждый стук — другой рот дома, — говорит он. — "
                "Первый — дерево. Второй — ладонь. Третий — горло. "
                "Ты позвал. Я открыл. Или дом открыл меня."
            )
            if flags.get("note_read"):
                print("— Записка врала не полностью. Она просто не успела стать мольбой.")
            print("\n=== Концовка: Разговор о пороге ===")
            return "end"

        if (t == "4" or has_any(t, "камень", "удар")) and "камень" in inventory:
            print(
                "\nКамень в кулаке. Он видит. — Ударишь — останешься один. "
                "Отпустишь — останемся вместе."
            )
            hit = input("Ударить? (да/нет): ")
            if normalize(hit) in ("да", "д", "yes", "y"):
                print("\nКамень о пол. Кресло пусто. Дом — только ты.")
                print("\n=== Концовка: Один ===")
            else:
                print(f"\nПальцы разжимаются. — Храбрый выбор, {name}.")
                print("\n=== Концовка: Доверие ===")
            return "end"

        if (t == "5" or has_any(t, "записк")) and "записка" in inventory:
            print(
                "\nОн читает то, что сам оставил — или ты. "
                "— Ключ найден. Можно не ждать вечно."
            )
            print("\n=== Концовка: Письмо доставлено ===")
            return "end"

        if (t == "6" or has_any(t, "пластинка")) and "пластинка" in inventory:
            print(
                "\nПластинка в щель подлокотника. Щелчок. В стене — ниша "
                "с запахом дождя, не гнили."
            )
            print(f"— Выход, о котором я забыл, {name}. Идти или остаться — оба пути честны.")
            choice = input("Выйти через нишу? (да/нет): ")
            if normalize(choice) in ("да", "д", "yes", "y"):
                print("\nДождь без неба. Дом остаётся сном.")
                print("\n=== Концовка: Скрытый выход ===")
            else:
                print("\nНиша закрывается. Кресло скрипит рядом.")
                print("\n=== Концовка: Осознанный круг ===")
            return "end"

        if has_any(t, "кукл") and "кукла" in inventory:
            print("\nОн смотрит на куклу. — Это не я. Это то, что играло в меня, когда я был меньше боли.")
            continue
        if has_any(t, "билет") and "билет" in inventory:
            print("\n— Поезд ушёл. Билет — чтобы помнить, что уход возможен на бумаге.")
            continue
        if flags.get("lurker_repelled") and has_any(t, "шкаф", "тень"):
            print("\n— Спасибо за низ. Редко кто приходит с остротой и уходит целым.")
            continue

        print("\nНомер из списка или предмет, который у тебя есть.")


