def finish_ending(title, state, extra_lines=None):
    name = state["name"]
    body = ENDING_TEXTS.get(title, "")
    if "{name}" in body:
        body = body.format(name=name)
    print(f"\n=== Концовка: {title} ===")
    if extra_lines:
        for line in extra_lines:
            print(line)
        print()
    if body:
        print(body)
    inv = state["inventory"]
    if inv:
        print("\nС собой в конце: " + ", ".join(sorted(inv)) + ".")
    print(f"\nСпасибо за игру. (v{VERSION})")
    return "end"


