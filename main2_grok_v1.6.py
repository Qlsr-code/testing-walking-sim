VERSION = "1.6"

# ── утилиты ──────────────────────────────────────────────────


def normalize(text):
    return (text or "").strip().lower()


def has_any(text, *words):
    t = normalize(text)
    return any(w in t for w in words)


def yes(raw):
    return normalize(raw) in ("да", "д", "yes", "y")


def knows_key_hint(flags):
    return any(
        flags.get(k)
        for k in ("note_read", "lock_hint_front", "lock_hint_back", "whisper_key_hint")
    )


def add_item(state, item, flag=None, message=None):
    state["inventory"].add(item)
    if flag:
        state["flags"][flag] = True
    if message:
        print(message)


def has_item(state, item):
    return item in state["inventory"]


def flag(state, name, value=None):
    if value is None:
        return state["flags"].get(name)
    state["flags"][name] = value
    return value


# ── мета-команды (не ломают сцену) ───────────────────────────

META_INVENTORY = frozenset({"инвентарь", "вещи", "сумка", "инв", "inv", "i"})
META_HELP = frozenset({"помощь", "help", "?", "хелп", "х"})
META_LOOK = frozenset({"осмотреться", "осмотр", "look", "оглядеться"})


def print_help():
    print(
        "\n── подсказка ──────────────────────────────\n"
        "  Номера (1, 2, 3…) — крупные действия.\n"
        "  Слова из описания — осмотр, взять, использовать, слушать.\n"
        "  «инвентарь» (или «вещи», «i») — список вещей.\n"
        "    Это не выбор сцены: после просмотра всё остаётся как было.\n"
        "  «осмотреться» — снова описание места.\n"
        "  «помощь» — этот текст.\n"
        "Не всё лежит на виду. Часть находок — просто мусор.\n"
        "────────────────────────────────────────────"
    )


def show_inventory(state):
    inv = state["inventory"]
    print("\n── с собой ─────────────────────────────────")
    if not inv:
        print("  (пусто)")
    else:
        for item in sorted(inv):
            print(f"  • {item}")
    print(
        "────────────────────────────────────────────\n"
        "Инвентарь только показывает вещи. Сцена не сброшена —\n"
        "можешь сразу продолжить осмотр или ввести номер действия."
    )


def try_meta(raw, state, describe_fn):
    """
    Глобальные команды. True — уже обработано, цикл сцены просто continue.
    Не пересекается с нумерованными выборами сцены.
    """
    t = normalize(raw)
    if t in META_INVENTORY:
        show_inventory(state)
        return True
    if t in META_HELP:
        print_help()
        return True
    if t in META_LOOK or t == "":
        if t == "":
            return False
        describe_fn()
        return True
    return False


def print_menu(lines, free_hint_num):
    """lines: список строк пунктов; free_hint_num — номер «пустой» подсказки."""
    for line in lines:
        print(line)
    print(
        f"{free_hint_num}. …кажется, здесь можно задержаться "
        f"дольше, чем подсказывают цифры"
    )


def free_hint_response():
    print(
        "\nТы медлишь. Цифры — лишь грубые тропы. "
        "Имена вещей из описания, касания, «осмотреть», «снять», "
        "«открыть», «слушать» — всё это тоже ходы. "
        "Сцена никуда не делась. Действуй, когда будешь готов."
    )


def parse_intent(raw):
    t = normalize(raw)
    if not t:
        return "empty"
    if has_any(t, "слушать", "прислуша"):
        return "listen"
    if has_any(
        t,
        "использовать", "применить", "открыть", "ударить", "вставить",
        "сломать", "толкнуть", "потянуть", "пнуть", "ковыр", "поддеть",
        "снять", "сорвать", "стянуть", "отодвинуть", "зажечь", "постучать",
        "сесть", "лечь", "порыться", "пошарить", "почистить", "протереть",
        "развернуть", "сложить", "ударить", "пнуть",
    ):
        return "use"
    if has_any(t, "взять", "поднять", "подобрать", "забрать", "сдвинуть", "достать", "выдернуть"):
        return "take"
    if has_any(
        t,
        "осмотреть", "посмотреть", "глянуть", "заглянуть", "проверить",
        "трогать", "тронуть", "потрогать", "пощупать", "потрогать",
    ):
        return "examine"
    if has_any(t, "стучать", "постучать", "стук"):
        return "knock"
    if has_any(t, "обойти", "кругом"):
        return "go_around"
    if has_any(t, "войти", "пройти внутрь"):
        return "enter"
    if has_any(t, "уйти", "уходить", "сбежать", "выйти", "наружу"):
        return "leave"
    return "keyword"


